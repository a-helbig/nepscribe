#' function that generates the scripts
#'
#' @keywords internal
#' @noRd
gen_script <- function(datapath_conv, datapath_local, suf_version, dataformat, subformat, datalist, prio, english, set_missings, parallel, further_training, education, children, work_exp, unemp_exp){
      sc <- toupper(identify_sc(datapath_conv))
      # if prio tab hasnt been clicked, we want to load the static element from constants. if prio is clicked we use the inputs returned value. This is necessary because inputs often do not return their return value when they are hidden behind a tab that wasnt clicked yet.
      if (is.null(prio) || length(prio) == 0) {
        prio <- if (sc != "SC5") .labels_sc3_4_6 else .labels_sc5
      }
      prio_var <- as.numeric(stringr::str_extract_all(prio, "\\d{2}"))
      # main employment episode selected by the respondent (th14599_g2), used in the prioritisation where available (not in SC5)
      has_mainemp <- sc %in% c("SC3", "SC4", "SC6")
      mainemp_ds <- if (sc == "SC4") "pTargetCATI" else "pTarget"
      # Biography-based format: all months are only needed for work and unemployment experience.
      # Without them, the monthly data are reduced to the interview months before the prioritisation (faster).
      allmonths <- isTRUE(work_exp) || isTRUE(unemp_exp)
      mainemp_txt <- if (has_mainemp) paste0("the main employment episode selected by the respondent (th14599_g2 in ", mainemp_ds, ", only in the waves where it is available and not filled across waves), ") else ""

      if(dataformat== "R" & subformat == "Harmonized Spell Format"){
        chapter <- 5 + length(datalist) # fixed number of chapters for main person-year-dataset preparation
        scripts <- c(
          paste0("# NEPScribe R base script to transform NEPS ", sc, " SUF data into a person-year format."),
          "",
          "# This is a basic data preparation script that generates a dataset in a person-year-format by taking the edited episodes from the NEPS SUF Biography file as a baseline (biography-based format).",
          "# Please carefully check each line and make sense of it. Edits to the script that fit your research project\u2019s needs are probably necessary and recommended.",
          "",
          "# !ATTENTION!",
          paste0("# If you want access to within spell variation across waves, spell related longitudinal information should be joined via 'ID_t', 'wave' and 'splink' after step 5, when the person-year structure has been generated and after dropping harmonized episodes in the spell files."),
          "# When using the 'Additional variables' function in the NEPScribe app, this procedure is applied automatically. This ensures that time-varying spell information is preserved. However, it requires careful handling of different missing value codes that arise from filtering or data issues.",
          "",
          "",
          cohort_notes(sc, "#"), # cohort-specific notes (results from testing SC3-SC5)
          "# Approach:",
          "",
          "# 1. Step: Load the Biography dataset as a base for the person-year-dataset and compile start and end date and generate a duration variable.",
          "",
          paste0("# 2. Step: Prepare the variables for the spell prioritisation. The type of vocational training (spVocTrain) is merged to the biography data. The working hours reported at each interview (subspells in spEmp)", if(has_mainemp) " and the main employment episode selected by the respondent", " are prepared and merged at the interview months in step 4."),
          "",
          "# 3. Step: Expand the data to a monthly format by multiplying each row of each respondent with the spell length in month (dur variable). This expansion to a month format is needed since there is no wave-specific information for episodes in the biography file but only one observation per episode with start and end date. To identify which episode represents the main activity at each interview date (and therefore wave) this reshape is needed. It serves as the basis for the following steps.",
          "",
          paste0("# 4. Step: Prepare the interview months (from the CohortProfile dataset) and merge the information for the spell prioritisation at these months: the working hours reported at that interview", if(has_mainemp) " and the main employment episode selected by the respondent", ".", if(!allmonths) " Then only the interview months are kept, because no indicator that needs all months (work or unemployment experience) was selected.", ""),
          "",
          paste0("# 5. Step: Spell prioritisation and person-year dataset. Sort the months of each respondent by determined spell order, ", mainemp_txt, "main/side episode (descending), working hours (descending) and splink (ascending order in which the episodes were reported; within a spell module, earlier reported episodes usually started earlier), and keep the first spell per person and month. ", if(allmonths) "Work and/or unemployment experience are computed over all months, then only the interview months are kept. ", "The result is a dataset with one row per wave of each respondent (what we call: 'person-year-dataset'), with the wave variable from the CohortProfile dataset. You may edit the sort order according to your research question(s)."),
          "",
          "# Additional data preparation steps may vary based on the settings configured in the Transform Data tab of the NEPScribe app.",
          "",
          "# Package Information and Script Formatting:",
          "# Script uses mostly dplyr due to its simplicity and sometimes base R for performance reasons. ",
          "# The code might need new indentation and formatting: Try Strg+A and then Strg+Shift+A in RStudio.",
          "",
          "rm(list = ls())",
          "",
          "# Packages ----------------------------------------------------------------",
          "list.of.packages <- c('dtplyr','haven','dplyr','tidyr','janitor','readstata13','stringr', 'remotes')",
          "new.packages <- list.of.packages[!(list.of.packages %in% installed.packages()[,'Package'])] # check if required packages are in installed packages on this machine",
          "if(length(new.packages)) install.packages (new.packages) # if new.packages contains sth and thus length is > 0, install those new packages",
          "",
          "# Install nepstools if not installed (package needs to be installed seperately from github) ",
          "if(!'nepstools' %in% installed.packages()) {",
          " remotes::install_github('a-helbig/nepstools')",
          "}",
          "",
          "# Add nepstools to list.of.packages",
          "list.of.packages <- append(list.of.packages, 'nepstools')",
          "invisible(lapply(list.of.packages, library, character.only = TRUE))",
          "",
          if(nchar(datapath_local)>0) paste0("datapath = ","'",datapath_local,"/","'"),
          if(nchar(datapath_local)==0)"datapath = \"\" # Specify local datapath here",
          if(nchar(datapath_local)>0) paste0("suf_version = ", "'", suf_version,"'", " # Please adjust if necessary"),
          if(nchar(datapath_local)==0)paste0("suf_version = ", "'", suf_version, "'", " # Please adjust if necessary"),
          paste0("english = ", english),
          paste0("sc = ", "'",sc,"'"),
          "",
          "# 1. Base: Biography file ---------------------------------------------------------------------",
          "",
          "# We take the edited episodes from the Biography file as a baseline for our person-year dataset.",
          "",
          "bio <- read_neps(paste0(datapath, '/', sc, '_Biography_D_', suf_version,'.dta'), english = english) |> ",
          "  replace_values_with_na() # We need to set missings in the biography data to get only positive values in the duration variable ('dur') generated in the next step. We need this 'dur' variable later for expanding the dataset to a monthly structure", #- in contrast we wont set missings in employment and voctrain data in order to get the same prioritisation as in stata and to preserve the possibility in stata to have extended missings (these extended missings otherwise would have an impact on the ordering in stata prep compared to Rs prep)
          "",
          "# Generate episode dates variables: transform date vars to one variable in the format: 'months since 1960' and get rid of episodes with missing date values. ",
          "bio <- bio |> ",
          "  mutate(start=((starty-1960)*12)+startm-1,",
          "         end=((endy-1960)*12)+endm-1,",
          "         dur = end-start+1)  |> ",
          "  filter(!is.na(start) & !is.na(end)) |> ",
          "  select(-startm,-starty,-endm,-endy)",
          "",
          "# The wave variable of the Biography file only indicates in which wave an episode was reported. It is not needed, because the waves of the person-year data come from the interview months in CohortProfile (step 4).",
          "bio <- bio |> select(-wave)",
          "",
          "# Assign varlabels to variables",
          if(english)"attr(bio$start, 'label') <- 'Start date'",
          if(english)"attr(bio$end, 'label') <- 'End date'",
          if(english)"attr(bio$dur, 'label') <- 'Duration'",
          if(!english)"attr(bio$start, 'label') <- 'Startdatum'",
          if(!english)"attr(bio$end, 'label') <- 'Enddatum'",
          if(!english)"attr(bio$dur, 'label') <- 'Dauer'",
          "",
          "# 2. Variable preparation for spell prioritisation ---------------------------------------------------------------------",
          "",
          "# Prepares the variables used to rank parallel episodes in step 5. Variables that apply to the whole episode are joined here; variables reported per wave are kept and joined at the interview months in step 4.",
          "",
          "# -- 2.1 Type of vocational training --",
          if(sc == "SC6")"# We require the type of vocational training for the prioritisation process of vocational training spells in step 5. Thus we join voctrain data, recode type of voc. training (different variable in Wave 1: ts15201_v1), reduce to harmonized episodes (subspell==0) and join it to biography data.",
          if(sc == "SC6")"suppressWarnings({ # warnings are suppressed here because case_match throws a warning due to conflicting variable labels in ts15201 and ts15201_v1. This doesnt matter, because in the new variable 'vt_typ' the variable labels from ts15201 are being used and that is preferable in most cases. Change this if neccessary.",
          if(sc == "SC6")"voctrain <- read_neps(paste0(datapath, '/', sc, '_spVocTrain_D_', suf_version,'.dta'), col_select = c('ID_t', 'splink', 'subspell', 'ts15201_v1', 'ts15201'), english = english) |> ",
          if(sc == "SC6")"  mutate(ts15201_v1 = case_match(ts15201_v1, # here the codes from the old voctrain-type var from wave 1 (ts15201_v1) are aligned with the new voctrain-type var ts15201 from wave 2+",
          if(sc == "SC6")"  2 ~ 3, ",
          if(sc == "SC6")"  3 ~ 4, ",
          if(sc == "SC6")"  4 ~ 5, ",
          if(sc == "SC6")"  5 ~ 6, ",
          if(sc == "SC6")"  6 ~ 9, ",
          if(sc == "SC6")"  7 ~ 10, ",
          if(sc == "SC6")"  8 ~ 15, ",
          if(sc == "SC6")"  9 ~ 16, ",
          if(sc == "SC6")"  10 ~ 11, ",
          if(sc == "SC6")"  11 ~ 12, ",
          if(sc == "SC6")"  12 ~ 13, ",
          if(sc == "SC6")"  13 ~ 14, ",
          if(sc == "SC6")"  14 ~ 17,",
          if(sc == "SC6")"  .default = ts15201_v1),",
          if(sc == "SC6")"  # Replace vttyp with recoded ts15201_v1 where vttyp is -54 (wave 1)",
          if(sc == "SC6")"  vt_typ = ts15201,",
          if(sc == "SC6")"  vt_typ = if_else(vt_typ == -54, ts15201_v1, vt_typ)) |>",
          if(sc == "SC6")"  filter(subspell == 0) |> ",
          if(sc == "SC6")"  select(-ts15201,-ts15201_v1, -subspell)",
          if(sc == "SC6")"})",
          if(sc %in% c("SC3","SC4","SC5"))"# We require the type of vocational training for the prioritisation process of spells in step 5. Thus we load voctrain data, reduce to harmonized episodes (subspell==0) and join it to biography data.",
          if(sc %in% c("SC3","SC4","SC5")) "voctrain <- read_neps(paste0(datapath, '/', sc, '_spVocTrain_D_', suf_version,'.dta'), english = english, col_select = c('ID_t', 'splink','subspell', 'ts15201')) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"mutate(vt_typ = ts15201) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"filter(subspell == 0) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"select(-ts15201, -subspell)",
          "",
          "bio <- left_join(bio, voctrain, by=c('ID_t', 'splink'))",
          "rm(voctrain)",
          "",
          "# -- 2.2 Working hours --",
          "# Parallel employment episodes are ranked by their working hours in step 5. The subspells in spEmp hold the working hours reported at each interview. They are joined at the interview months in step 4 (via ID_t, wave and splink), so that parallel episodes at an interview month are ranked by the working hours reported at that interview.",
          if(sc == "SC6") "cols <- c('ID_t', 'wave', 'splink', 'spell','subspell', 'spstat', 'ts23223_g1')"
          else "cols <- c('ID_t', 'wave', 'splink', 'spell','subspell', 'spstat', 'ts23223')",
          "",
          "# Read NEPS dataset with nepstools::read_neps()",
          "emp <- read_neps(paste0(datapath, '/', sc, '_spEmp_D_', suf_version,'.dta'), col_select = cols, english = english)",
          "",
          if (sc == "SC6")  "emp <- emp |> ",
          if (sc == "SC6")    "rename(ts23223 = ts23223_g1)",
          "",
          "# Two codes of ts23223 carry information: -20 (more than 90 hours per week) is set to 90, so that these episodes rank highest, and -21 (no fixed working hours) is set to missing. All other missing codes are set to missing below.",
          "emp$ts23223[emp$ts23223 == -21] <- NA # no fixed working hours",
          "emp$ts23223[emp$ts23223 == -20] <- 90 # more than 90 hours per week",
          "",
          "# Harmonized records are dropped, and missing working hours are filled with valid values from preceding or subsequent subspells of the same episode.",
          "emp_wave <- emp |>",
          "  filter(!spstat %in% c(30, 31)) |>",
          "  replace_values_with_na(vars = 'ts23223') |>",
          "  dtplyr::lazy_dt() |>",
          "  group_by(ID_t, splink) |>",
          "  arrange(ID_t, splink, subspell) |>",
          "  tidyr::fill(ts23223, .direction = 'downup') |>",
          "  ungroup() |>",
          "  as_tibble() |>",
          "  select(ID_t, wave, splink, ts23223)",
          "rm(emp)",
          "",
          if(has_mainemp) "# -- 2.3 Main employment episode selected by the respondent --",
          if(has_mainemp) "# In the waves where it is available, the link th14599_g2 marks the episode the respondent selected as main employment. It is preferred over other parallel employment episodes in step 5. It refers to an interview, so it is prepared here and joined at the interview months in step 4. It is not filled across waves.",
          if(has_mainemp) paste0("mainemp <- read_neps(paste0(datapath, '/', sc, '_", mainemp_ds, "_D_', suf_version,'.dta'), col_select = c('ID_t', 'wave', 'th14599_g2'), english = english) |>"),
          if(has_mainemp) "  filter(th14599_g2 > 0) |>",
          if(has_mainemp) "  mutate(splink = as.numeric(th14599_g2), mainemp = 1) |>",
          if(has_mainemp) "  select(ID_t, wave, splink, mainemp)",
          if(has_mainemp) "",
          "# 3. Expand to monthly structure for spell prioritisation -------------------------------------------",
          "",
          "# The expand function will generate one row for each month in the duration variable ('dur'). When we then group by ID_t and splink, we can generate a month variable (measured in months since january 1960) by taking the start date of each spell and adding the grouped row number (-1) to it. When respondents have reported parallel spells, this will lead to a dataset with duplicated months within person. Later, in step 5, the dataset is specifically ordered and then reduced to unique months, a process we call 'spell prioritisation.'",
          "bio <-  nepstools::expand(bio, dur)",
          "",
          "# Create indicator 'month' ",
          "bio <- bio |>",
          "  lazy_dt() |> # because of now very large data frame use this function from dtplyr for fastest R solution outside the data.table package",
          "  arrange(ID_t, splink) |>",
          "  group_by(ID_t, splink) |>",
          "  mutate(month = start + row_number() - 1) |>",
          "  ungroup() |>",
          "  as_tibble()",
          "",
          "# 4. Interview months and information for the spell prioritisation --------------------------",
          "",
          "# Parallel episodes are only resolved for the months in which an interview took place, with the information reported at that interview. This step prepares the interview months and this information.",
          "",
          "# -- Interview months from CohortProfile --",
          "cohort_profile <- read_neps(paste0(datapath, '/', sc, '_CohortProfile_D_', suf_version,'.dta'), english = english)",
          "",
          "# Select Variables, generate a month variable for the interview date and filter for participation waves and non-NA month rows.",
          if(sc == "SC6")" cohort_profile <- cohort_profile |>
      select(ID_t, wave, tx8601y, tx8601m, tx80220) |>
      rename(tx8600m = tx8601m, tx8600y = tx8601y) |> # renaming date variables is only done for internal NEPScribe handling of different variable names across starting cohorts",
          if(sc %in% c("SC4", "SC5")) "cohort_profile <- cohort_profile |>
        select(ID_t, wave, tx8600y, tx8600m, tx80220) |> ",
          if(sc == "SC3") "cohort_profile <- cohort_profile |>
        select(ID_t, wave, tx8601y, tx8601m, tx80220) |>
        rename(tx8600m = tx8601m, tx8600y = tx8601y) |> # renaming date variables is only done for internal NEPScribe handling of different variable names across starting cohorts",
          "replace_values_with_na() |>",
          "mutate(month = ((tx8600y - 1960) * 12) + tx8600m - 1)  |>",
          "filter(tx80220 == 1 & !is.na(month)) |>",
          "select(-tx8600y, -tx8600m, -tx80220)",
          "",
          if(sc == "SC5")"# In SC5, a few respondents have the same interview month in two waves. Keep only the first of these waves, otherwise the same spell would be assigned to both waves.",
          if(sc == "SC5")"cohort_profile <- cohort_profile |>",
          if(sc == "SC5")"  arrange(ID_t, wave) |>",
          if(sc == "SC5")"  distinct(ID_t, month, .keep_all = TRUE)",
          if(sc == "SC5")"",
          "# -- Mark the interview months in the monthly data --",
          "# wave is the wave of the interview in that month (NA in all other months).",
          "bio <- left_join(bio, cohort_profile, by = c('ID_t', 'month'))",
          "rm(cohort_profile)",
          "",
          "# -- Working hours reported at the interview --",
          "bio <- left_join(bio, emp_wave, by = c('ID_t', 'wave', 'splink'))",
          "rm(emp_wave)",
          paste0("# At some interview months an episode has no subspell, e.g. because it started in the interview month but was only reported at the next interview",
                 if (sc %in% c("SC3", "SC4", "SC5")) paste0(" or the interview collected no spell data (", c(SC3 = "school waves", SC4 = "school waves", SC5 = "online waves")[[sc]], ")"),
                 ". There the working hours of the nearest interview of the same episode are used: those of the preceding interview, or of the following one if there is none."),
          "bio <- bio |>",
          "  dtplyr::lazy_dt() |>",
          "  arrange(ID_t, splink, month) |>",
          "  group_by(ID_t, splink) |>",
          "  tidyr::fill(ts23223, .direction = 'downup') |>",
          "  ungroup() |>",
          "  as_tibble()",
          "",
          if(has_mainemp) "# -- Main employment episode selected by the respondent --",
          if(has_mainemp) "# Joined at the interview months (prepared in step 2.3).",
          if(has_mainemp) "bio <- left_join(bio, mainemp, by = c('ID_t', 'wave', 'splink'))",
          if(has_mainemp) "rm(mainemp)",
          if(has_mainemp) "",
          if(!allmonths) "# -- Reduce to the interview months --",
          if(!allmonths) "# Only the interview months become person-years. All other months would only be needed for work or unemployment experience, which were not selected. Dropping them here makes the prioritisation in step 5 much faster.",
          if(!allmonths) "bio <- bio |> filter(!is.na(wave))",
          if(!allmonths) "",
          "# 5. Spell prioritisation and person-year dataset ------------------------------------------",
          "",
          "# To construct a person-year dataset where each row corresponds to one wave for each individual, a spell prioritisation process is useful for identifying the principal spell in cases where multiple spells occur simultaneously.",
          "",
          "# -- Ranks and sorting --",
          paste0("# We  may recode licences courses and ihk courses to value ", ifelse(sc != "SC5", "31", "37"), " to place it behind ", ifelse(sc != "SC5", "xmodule", "internship")," episodes in the prioritisation order, because these types of episodes are typically rather side spells than main spells and thus considered of lesser importance in many research projects with regard to spell prioritisation. You may change that."),
          licence_course_note(sc, "#"),
          "",
          "bio <- bio |>",
          "  mutate(prio = sptype,",
          paste0("  prio = ifelse(vt_typ %in% 13:14, ", ifelse(sc != "SC5", "31", "37"),", sptype),"),
          "  prio = case_when(",
          paste("  prio == ",prio_var[1]," ~ 1,"),
          paste("  prio == ",prio_var[2]," ~ 2,"),
          paste("  prio == ",prio_var[3]," ~ 3,"),
          paste("  prio == ",prio_var[4]," ~ 4,"),
          paste("  prio == ",prio_var[5]," ~ 5,"),
          paste("  prio == ",prio_var[6]," ~ 6,"),
          paste("  prio == ",prio_var[7]," ~ 7,"),
          paste("  prio == ",prio_var[8]," ~ 8,"),
          paste("  prio == ",prio_var[9]," ~ 9,"),
          paste("  prio == ",prio_var[10]," ~ 10,"),
          if(sc == "SC5")paste("  prio == ",prio_var[11]," ~ 11,"),
          "  TRUE ~ NA_real_  # For values not specified, set to NA",
          "))",
          "",
          "# Recode these variables in order to use them in the prioritisation process.",
          "bio$spms[bio$spms == 2] <- 0",
          "bio$spms[is.na(bio$spms)] <- 0",
          "bio$worktime <- as.numeric(bio$ts23223)",
          "bio$worktime[is.na(bio$worktime)] <- 0",
          if(has_mainemp) "bio$mainemp[is.na(bio$mainemp)] <- 0 # recode missings to 0 for sorting",
          "bio$spms <- as.numeric(bio$spms) # as.numeric for sorting",
          "",
          if(!has_mainemp) "# To prioritize parallel spells, we consider the following variables in this order of relevance: prio (order of the spell types from NEPScribe), spms (main vs side episode), working hours and splink (order of reporting). The working hours only distinguish between employment episodes. Edit if necessary.",
          if(has_mainemp) "# To prioritize parallel spells, we consider the following variables in this order of relevance: prio (order of the spell types from NEPScribe), mainemp (main employment selected by the respondent), spms (main vs side episode), working hours and splink (order of reporting). mainemp and the working hours only distinguish between employment episodes. Edit if necessary.",
          "",
          if(!has_mainemp) "bio <- bio[order(bio$ID_t, bio$month, bio$prio, -bio$spms, -bio$worktime, bio$splink),]",
          if(has_mainemp) "bio <- bio[order(bio$ID_t, bio$month, bio$prio, -bio$mainemp, -bio$spms, -bio$worktime, bio$splink),]",
          "",
          if(parallel) gen_parallel_spells_r(format="harmonized"),
          "# -- Keep the prioritised spell per person and month --",
          "# Remove duplicates, keeping only the first row for each combination of ID_t and month (base R here because it is faster than dplyr with row_number()).",
          "bio <- bio[!duplicated(bio[c('ID_t', 'month')]), ]",
          "",
          if(allmonths) "# -- Work and unemployment experience --",
          if(allmonths) "# These indicators count all months up to each interview, so they are computed before the reduction to the interview months.",
          if(allmonths) "",
          if(work_exp)"# Generate work experience in months",
          if(work_exp)"bio <- bio  |> ",
          if(work_exp)  "mutate(emp = ifelse(sptype == 26, 1, NA_real_)) |>",
          if(work_exp)  "arrange(ID_t) |>",
          if(work_exp)  "group_by(ID_t)  |> ",
          if(work_exp)  "mutate(work_exp = cumsum(replace_na(emp, 0))) |>",
          if(work_exp)  "ungroup()",
          if(work_exp)"",
          if(work_exp)"attr(bio$work_exp, 'label') <- 'Work experience'",
          if(work_exp)"bio <- bio |> select(-emp)",
          if(work_exp)"",
          if(unemp_exp)"# Generate unemployment experience in months",
          if(unemp_exp)"bio <- bio  |> ",
          if(unemp_exp)  "mutate(unemp = ifelse(sptype == 27, 1, NA_real_)) |>",
          if(unemp_exp)  "arrange(ID_t) |>",
          if(unemp_exp)  "group_by(ID_t)  |> ",
          if(unemp_exp)  "mutate(unemp_exp = cumsum(replace_na(unemp, 0))) |>",
          if(unemp_exp)  "ungroup()",
          if(unemp_exp)"",
          if(unemp_exp)"attr(bio$unemp_exp, 'label') <- 'Unemployment experience'",
          if(unemp_exp)"bio <- bio |> select(-unemp)",
          if(unemp_exp)"",
          "# -- Person-year dataset --",
          if(allmonths) "# Reduce to the interview months: only they become person-years (the other months were only kept yet, in order to generate variables for work or unemployment experience).",
          if(allmonths) "bio <- bio |> filter(!is.na(wave))",
          if(!allmonths) "# The data were already reduced to the interview months in step 4.",
          "# Helper variables that are not required anymore are dropped.",
          paste0("bio <- bio |> select(-spms, -prio, -ts23223, -vt_typ", if(has_mainemp) ", -mainemp", ", -worktime, -month, -splast) |> relocate(ID_t, wave)"),
          "",
          "# Check: one row per respondent and wave",
          "if (any(duplicated(bio[c('ID_t', 'wave')]))) stop('Duplicated waves found.')",
          "",
          if(sc %in% c("SC3", "SC4", "SC5")) gen_spells_reported_r(sc, format = "harmonized"), # not needed in SC6: every interview has spell data
          if(length(datalist)>0) generate_strings(datalist, english, format = "harmonized"), # add variables feature
          if(length(datalist)>0) ""
        )

      if (set_missings) {
        chapter <- chapter + 1
        scripts <- c(
          scripts,
          paste0("# ", chapter, ". Additional Settings------------------------------------"),
