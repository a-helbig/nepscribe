          chapter <- chapter + 1
          scripts <- c(
            scripts,
            paste0("********************************************************************************"),
            paste0("* ", chapter, " Additional Settings"),
            paste0("********************************************************************************")
          )
        }

        if (set_missings) {
          scripts <- c(
            scripts,
            "",
            "* Set missings for all variables",
            "mvdecode _all, mv(-98 = .a \\ -97 = .b \\ -54 = .c \\ -55 = .d ) // alternatively one can use the 'nepsmiss' function from nepstools ado",
            ""
          )
        }

        if (english) {
          scripts <- c(
            scripts,
            "",
            "* Switch variable and value labels to english",
            "label language en",
            "",
            if (english) "label var start \"Date of episode start (in months since january 1960)\"",
            if (english) "label var end \"Date of episode end (months since january 1960)\"",
            if (english) "label var dur \"Duration of episode\""
          )
        }

      }
      return(scripts)
    }

