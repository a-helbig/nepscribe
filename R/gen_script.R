#' function that generates the scripts
#'
#' @keywords internal
#' @noRd
gen_script <- function(datapath_conv, datapath_local, suf_version, dataformat, subformat, datalist, prio, english, set_missings, parallel, further_training, education, children, work_exp, unemp_exp){
      sc <- toupper(identify_sc(datapath_conv))
      # if prio tab hasnt been clicked, we want to load the static element from constants. if prio is clicked we use the inputs returned value. This is necessary because inputs often do not return their return value when they are hidden behind a tab that wasnt clicked yet.
      if (is.null(prio) || length(prio) == 0) {
        prio <- if (sc != "SC5") .labels_sc3_4_6 else .labels_sc5
      }
      prio_var <- as.numeric(stringr::str_extract_all(prio, "\\d{2}"))

      if(dataformat== "R" & subformat == "Harmonized Spell Format"){
        chapter <- 6 + length(datalist) # fixed number of chapters for main person-year-dataset preparation
        scripts <- c(
          paste0("# NEPScribe R base script to transform NEPS ", sc, " SUF data into a person-year format."),
          "",
          "# This is a basic data preparation script that generates a dataset in a person-year-format by taking the harmonized spells from the NEPS SUF Biography file as a baseline.",
          "# Please carefully check each line and make sense of it. Edits to the script that fit your research project’s needs are probably necessary and recommended.",
          "# !ATTENTION!",
          "# If you want access to within spell variation across waves, spell related longitudinal information should be joined via 'ID_t', 'wave' and 'splink' after step 6, when the person-year structure has been generated and after dropping harmonized episodes in the spell files.",
          "# When using the 'Additional variables' function in the NEPScribe app, this procedure is applied automatically. This ensures that time-varying spell information is preserved. However, it requires careful handling of different missing value codes that arise from filtering or data issues.",
          "",
          "# Approach:",
          "",
          "# 1. Step: Load the Biography dataset as a base for the person-year-dataset and compile start and end date and generate a duration variable.",
          "",
          "# 2. Step: Load the Employment dataset and merge it to the biography dataset to access the working hours variable. This variable will be used in step 5 for the prioritisation of parallel employment episodes.",
          "",
          "# 3. Step: Load the VocTrain dataset and merge it to the biography dataset to access the vocational training type variable. This variable will also be used in the spell prioritisation process.",
          "",
          "# 4. Step: Expand the data to a monthly format by multiplying each row of each respondent with the spell length in month (dur variable). This expansion to a month format is needed since there is no wave-specific information for episodes in the biography file but only one observation per episode with start and end date. To identify which episode represents the main activity at each interview date (and therefore wave) this reshape is needed. It serves as the basis for the spell prioritisation process in the next step.",
          "",
          "# 5. Step: Spell prioritisation process. Sort the months of each respondent by determined spell order, main/side episode (descending), working hours (descending), duration (descending) and splink (ascending order in which the episodes were reported). You may edit this according to your research question(s).",
          "",
          "# 6. Step: Reduce rows in dataset to interview date months by loading the CohortProfile dataset and generating a month variable for each interview date. Then merge this dataset and the biography data by ID_t and month. This leads to a dataset with one row per wave of each respondent (what we call: 'person-year-dataset').",
          "",
          "# Additional data preparation steps may vary based on the settings configured in the Transform Data tab of the NEPScribe app.",
          "",
          "# Package Information and Script Formatting:",
          "# Script uses mostly dplyr due to its simplicity and sometimes base R for performance reasons. ",
          "# The code might need new indentation and formatting: Try Strg+A and then Strg+Shift+A in RStudio.",
          "",
          "rm(list = ls())",
          "",
          "# Packages ----------------------------------------------------------------",
          "list.of.packages <- c('dtplyr','haven','dplyr','tidyr','janitor','readstata13','stringr', 'remotes')",
          "new.packages <- list.of.packages[!(list.of.packages %in% installed.packages()[,'Package'])] # check if required packages are in installed packages on this machine",
          "if(length(new.packages)) install.packages (new.packages) # if new.packages contains sth and thus length is > 0, install those new packages",
          "",
          "# Install nepstools if not installed (package needs to be installed seperately from github) ",
          "if(!'nepstools' %in% installed.packages()) {",
          " remotes::install_github('a-helbig/nepstools')",
          "}",
          "",
          "# Add nepstools to list.of.packages",
          "list.of.packages <- append(list.of.packages, 'nepstools')",
          "invisible(lapply(list.of.packages, library, character.only = TRUE))",
          "",
          if(nchar(datapath_local)>0) paste0("datapath = ","'",datapath_local,"/","'"),
          if(nchar(datapath_local)==0)"datapath = \"\" # Specify local datapath here",
          if(nchar(datapath_local)>0) paste0("suf_version = ", "'", suf_version,"'", " # Please adjust if necessary"),
          if(nchar(datapath_local)==0)"suf_version = \"16-0-0\" # Please adjust if necessary",
          paste0("english = ", english),
          paste0("sc = ", "'",sc,"'"),
          "",
          "# 1. Base: Biography file ---------------------------------------------------------------------",
          "",
          "# We take the harmonized episodes from the biography file as a baseline for our person-year dataset.",
          "",
          "bio <- read_neps(paste0(datapath, '/', sc, '_Biography_D_', suf_version,'.dta'), english = english) |> ",
          "  replace_values_with_na() # We need to set missings in the biography data to get only positive values in the duration variable ('dur') generated in the next step. We need this 'dur' variable later for expanding the dataset to a monthly structure", #- in contrast we wont set missings in employment and voctrain data in order to get the same prioritisation as in stata and to preserve the possibility in stata to have extended missings (these extended missings otherwise would have an impact on the ordering in stata prep compared to Rs prep)
          "",
          "# Generate episode dates variables: transform date vars to one variable in the format: 'months since 1960' and get rid of episodes with missing date values. ",
          "bio <- bio |> ",
          "  mutate(start=((starty-1960)*12)+startm-1,",
          "         end=((endy-1960)*12)+endm-1,",
          "         dur = end-start+1)  |> ",
          "  filter(!is.na(start) & !is.na(end)) |> ",
          "  select(-startm,-starty,-endm,-endy)",
          "",
          "# Assign varlabels to variables",
          if(english)"attr(bio$start, 'label') <- 'Start date'",
          if(english)"attr(bio$end, 'label') <- 'End date'",
          if(english)"attr(bio$dur, 'label') <- 'Duration'",
          if(!english)"attr(bio$start, 'label') <- 'Startdatum'",
          if(!english)"attr(bio$end, 'label') <- 'Enddatum'",
          if(!english)"attr(bio$dur, 'label') <- 'Dauer'",
          "",
          "# 2. Employment info for spell prioritisation ---------------------------------------------------------------------",
          "",
          "# We need the working hours for the prioritisation process of parallel employment spells later in Step 5. Thus we join employment data, recode working hours and reduce to harmonized episodes (subspell==0) and join it to biography data.",
          if(sc == "SC6") "cols <- c('ID_t', 'splink', 'spell','subspell', 'ts23223_g1')"
          else "cols <- c('ID_t', 'splink', 'spell','subspell', 'ts23223')",
          "",
          "# Read NEPS dataset with nepstools::read_neps()",
          "emp <- read_neps(paste0(datapath, '/', sc, '_spEmp_D_', suf_version,'.dta'), col_select = cols, english = english) |>",
          "  filter(subspell == 0) ",
          "",
          if (sc == "SC6")  "emp <- emp |> ",
          if (sc == "SC6")    "rename(ts23223 = ts23223_g1)",
          "",
          "emp$ts23223[emp$ts23223 == -21] <- NA # work time not specified",
          "emp$ts23223[emp$ts23223 == -20] <- 90 # more than 90 hours per week",
          "",
          "bio <- left_join(bio, emp, by=c('ID_t', 'splink'))",
          "rm(emp)",
          "",
          "# 3. Vocational Training Preparation for spell prioritisation -----------------------------------------",
          "",
          if(sc == "SC6")"# We also require the type of vocational training for the prioritisation process of vocational training spells later in Step 4. Thus we join voctrain data, recode type of voc. training (different variable in Wave 1: ts15201_v1), reduce to harmonized episodes (subspell==0) and join it to biography data.",
          if(sc == "SC6")"suppressWarnings({ # warnings are suppressed here because case_match throws a warning due to conflicting variable labels in ts15201 and ts15201_v1. This doesnt matter, because in the new variable 'vt_typ' the variable labels from ts15201 are being used and that is preferable in most cases. Change this if neccessary.",
          if(sc == "SC6")"voctrain <- read_neps(paste0(datapath, '/', sc, '_spVocTrain_D_', suf_version,'.dta'), col_select = c('ID_t', 'splink', 'subspell', 'ts15201_v1', 'ts15201'), english = english) |> ",
          if(sc == "SC6")"  mutate(ts15201_v1 = case_match(ts15201_v1, # here the codes from the old voctrain-type var from wave 1 (ts15201_v1) are aligned with the new voctrain-type var ts15201 from wave 2+",
          if(sc == "SC6")"  2 ~ 3, ",
          if(sc == "SC6")"  3 ~ 4, ",
          if(sc == "SC6")"  4 ~ 5, ",
          if(sc == "SC6")"  5 ~ 6, ",
          if(sc == "SC6")"  6 ~ 9, ",
          if(sc == "SC6")"  7 ~ 10, ",
          if(sc == "SC6")"  8 ~ 15, ",
          if(sc == "SC6")"  9 ~ 16, ",
          if(sc == "SC6")"  10 ~ 11, ",
          if(sc == "SC6")"  11 ~ 12, ",
          if(sc == "SC6")"  12 ~ 13, ",
          if(sc == "SC6")"  13 ~ 14, ",
          if(sc == "SC6")"  14 ~ 17,",
          if(sc == "SC6")"  .default = ts15201_v1),",
          if(sc == "SC6")"  # Replace vttyp with recoded ts15201_v1 where vttyp is -54 (wave 1)",
          if(sc == "SC6")"  vt_typ = ts15201,",
          if(sc == "SC6")"  vt_typ = if_else(vt_typ == -54, ts15201_v1, vt_typ)) |>",
          if(sc == "SC6")"  filter(subspell == 0) |> ",
          if(sc == "SC6")"  select(-ts15201,-ts15201_v1, -subspell)",
          if(sc == "SC6")"})",
          if(sc %in% c("SC3","SC4","SC5"))"# We also require the type of vocational training for the prioritisation process of spells later in Step 5. Thus we join voctrain data, reduce to harmonized episodes (subspell==0) and join it to biography data.",
          if(sc %in% c("SC3","SC4","SC5")) "voctrain <- read_neps(paste0(datapath, '/', sc, '_spVocTrain_D_', suf_version,'.dta'), english = english, col_select = c('ID_t', 'splink','subspell', 'ts15201')) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"mutate(vt_typ = ts15201) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"filter(subspell == 0) |> ",
          if(sc %in% c("SC3","SC4","SC5"))"select(-ts15201, -subspell)",
          "",
          "bio <- left_join(bio, voctrain, by=c('ID_t', 'splink'))",
          "rm(voctrain)",
          "",
          "# 4. Expand to monthly structure for spell prioritisation -------------------------------------------",
          "",
          "# The expand function will generate one row for each month in the duration variable ('dur'). When we then group by ID_t and splink, we can generate a month variable (measured in months since january 1960) by taking the start date of each spell and adding the grouped row number (-1) to it. When respondents have reported parallel spells, this will lead to a dataset with duplicated months within person. Later, in step 5, the dataset is specifically ordered and then reduced to unique months, a process we call 'spell prioritisation.'",
          "bio <-  nepstools::expand(bio, dur)",
          "",
          "# Create indicator 'month' ",
          "bio <- bio |>",
          "  lazy_dt() |> # because of now very large data frame use this function from dtplyr for fastest R solution outside the data.table package",
          "  arrange(ID_t, splink) |>",
          "  group_by(ID_t, splink) |>",
          "  mutate(month = start + row_number() - 1) |>",
          "  ungroup() |>",
          "  as_tibble()",
          "",
          "# 5. Spell prioritisation process ----------------------------------------------------",
          "",
          "# To construct a person-year dataset where each row corresponds to one wave for each individual, a spell prioritisation process is useful for identifying the principal spell in cases where multiple spells occur simultaneously.",
          "",
          paste0("# We  may recode licences courses and ihk courses to value ", ifelse(sc != "SC5", "31", "37"), " to place it behind ", ifelse(sc != "SC5", "xmodule", "internship")," episodes in the prioritisation order, because these types of episodes are typically rather side spells than main spells and thus considered of lesser importance in many research projects with regard to spell prioritisation. You may change that."),
          "",
          "bio <- bio |>",
          "  mutate(prio = sptype,",
          paste0("  prio = ifelse(vt_typ %in% 13:14, ", ifelse(sc != "SC5", "31", "37"),", sptype),"),
          "  prio = case_when(",
          paste("  prio == ",prio_var[1]," ~ 1,"),
          paste("  prio == ",prio_var[2]," ~ 2,"),
          paste("  prio == ",prio_var[3]," ~ 3,"),
          paste("  prio == ",prio_var[4]," ~ 4,"),
          paste("  prio == ",prio_var[5]," ~ 5,"),
          paste("  prio == ",prio_var[6]," ~ 6,"),
          paste("  prio == ",prio_var[7]," ~ 7,"),
          paste("  prio == ",prio_var[8]," ~ 8,"),
          paste("  prio == ",prio_var[9]," ~ 9,"),
          paste("  prio == ",prio_var[10]," ~ 10,"),
          if(sc == "SC5")paste("  prio == ",prio_var[11]," ~ 11,"),
          "  TRUE ~ NA_real_  # For values not specified, set to NA",
          "))",
          "",
          "# Recode these 2 variables in order to use them in the prioritisation process (do it here due to speed issues later after the expanding).",
          "bio$spms[bio$spms == 2] <- 0",
          "bio$spms[is.na(bio$spms)] <- 0",
          "bio$worktime <- bio$ts23223",
          "bio$worktime[is.na(bio$ts23223)] <- 0",
          "",
          "# To prioritize multiple parallel spells, we consider multiple variables in the following order of relevance: prio, spms (main vs side episode), working hours, employment duration and splink. Edit if necessary.",
          "",
          "# Sort the data frame in this order",
          "bio$worktime <- as.numeric(bio$worktime) # as.numeric for sorting ",
          "bio$spms <- as.numeric(bio$spms) # as.numeric for sorting ",
          "bio <- bio[order(bio$ID_t, bio$month, bio$prio, -bio$spms, -bio$worktime, -bio$dur, bio$splink),]",
          "",
          if(parallel) gen_parallel_spells_r(format="harmonized"),
          "# Prioritisation: Remove duplicates, keeping only the first row for each group of combination of ID_t and month (base R here because its faster than dplyr solution with row_number()).",
          "bio <- bio[!duplicated(bio[c('ID_t', 'month')]), ]",
          "",
          "# Drop unnecessary variables",
          "bio <- bio |> select(-wave, -spms, -prio, -ts23223, -vt_typ) # drop wave variable from biography file here as there is only one wave for each episode which only indicates in which wave an episode was last reported, regardless of whether it was reported over multiple waves. In the next step the wave variable from cohort profile is added indicating all waves during which an episode was current.",
          "",
          if(work_exp)"# Generate work experience in months",
          if(work_exp)"bio <- bio  |> ",
          if(work_exp)  "group_by(ID_t)  |> ",
          if(work_exp)  "mutate(work_exp = sum(sptype == 26, na.rm = TRUE)) |>",
          if(work_exp)  "ungroup()",
          if(work_exp)"",
          if(unemp_exp)"# Generate unemployment experience in months",
          if(unemp_exp)"bio <- bio  |> ",
          if(unemp_exp)  "group_by(ID_t)  |> ",
          if(unemp_exp)  "mutate(unemp_exp = sum(sptype == 27, na.rm = TRUE)) |>",
          if(unemp_exp)  "ungroup()",
          if(unemp_exp)"",
          "# 6. Create person year format -------------------------------------",
          "",
          "# Finally we switch from a monthly format to a yearly format by taking the interview dates from cohort profile and left-joining the biography data to it.",
          "# This will keep only rows (months) in the bio dataset that correspond to actual interview dates from cohort profile. Finally this leads to a format with 1 row per year of a person where information is centered around each interview date.",
          "",
          "# Load interview dates from cohortprofile",
          "cohort_profile <- read_neps(paste0(datapath, '/', sc, '_CohortProfile_D_', suf_version,'.dta'), english = english)",
          "",
          "# Select Variables, generate a month variable for the interview date and filter for participation waves and non-NA month rows.",
          if(sc == "SC6")" cohort_profile <- cohort_profile |>
      select(ID_t, wave, tx8601y, tx8601m, tx80220) |>
      rename(tx8600m = tx8601m, tx8600y = tx8601y) |> # renaming date variables is only done for internal NEPScribe handling of different variable names across starting cohorts",
          if(sc %in% c("SC4", "SC5")) "cohort_profile <- cohort_profile |>
        select(ID_t, wave, tx8600y, tx8600m, tx80220) |> ",
          if(sc == "SC3") "cohort_profile <- cohort_profile |>
        select(ID_t, wave, tx8601y, tx8601m, tx80220) |>
        rename(tx8600m = tx8601m, tx8600y = tx8601y) |> # renaming date variables is only done for internal NEPScribe handling of different variable names across starting cohorts",
          "replace_values_with_na() |>",
          "mutate(month = ((tx8600y - 1960) * 12) + tx8600m - 1)  |>",
          "filter(tx80220 == 1 & !is.na(month)) |>",
          "select(-tx8600y, -tx8600m, -tx80220)",
          "",
          "# Inner join biography to cohort profile in order to keep only matches.",
          "bio <- inner_join(cohort_profile, bio, by=c('ID_t','month'))",
          "rm(cohort_profile)",
          "",
          "# Drop unnecessary vars",
          "bio <- bio |> ",
          "select(-worktime, -month, -splast)",
          "",
          if(length(datalist)>0) generate_strings(datalist, english, format = "harmonized"), # add variables feature
          if(length(datalist)>0) ""
        )

      if (education) {
        chapter <- chapter + 1
        scripts <- c(scripts, gen_qualification_prep_code_r(english, sc, chapter), "")
      }

      if (further_training) {
        chapter <- chapter + 1
        scripts <- c(scripts, further_training_gen_r(english, chapter), "")
      }

      if (children && sc %in% c("SC5", "SC6")) {
        chapter <- chapter + 1
        scripts <- c(scripts, gen_children_example_r_sc5_6(english, sc, chapter), "")
      }

      if (children && sc %in% c("SC3", "SC4")) {
        chapter <- chapter + 1
        scripts <- c(scripts, gen_children_example_r_sc3_4(english, sc, chapter), "")
      }

      if (set_missings) {
        chapter <- chapter + 1
        scripts <- c(
          scripts,
          paste0("# ", chapter, " Additional Settings------------------------------------"),
          "",
          "# set missings for all vars",
          "bio <- replace_values_with_na(bio)"
        )
      }

      }

      # NEPScribe R base script to transform NEPS SUF data from a spell format into a person-year structured format.
      # Harmonized biography spells are ignored; original spell files are used instead.

      if(dataformat== "R" & subformat == "Original Subspell Format"){
        chapter <- 3 + length(datalist)
        scripts <- c("# NEPScribe R base script to transform NEPS SUF data from a spell format into a person-year format.",
                     "# This is a basic data preparation script that generates a dataset in a person-year-format by taking the original sub-spell information from the NEPS SUF spell datasets as a baseline.",
                     "# Harmonized spells from the biography dataset are ignored.",
                     "",
                     "# !ATTENTION!",
                     "# Please carefully check each line and make sense of it. Edits to the script that fit your research project’s needs are probably necessary and recommended.",
                     "# Pay special attention to key variables of interest in the different sub-spells to see how these data have been collected and consider missings in sub-spells. Missings can be dealt with by replacing them with valid values from other sub-spells. Routines for that are partially provided in the script.",
                     "",
                     "# Approach:",
                     "",
                     "# 1. Step: Append all spell datasets into one dataset with the original sub-spell information.",
                     "",
                     "# 2. Step: Recode variables on the type of vocational training and working hours of employment. This information is used in the spell prioritisation process. Also recode start and end date information by replacing season codes and dropping spells with missing date information. At this point only sub-spells at the time of the interview date are kept (no harmonized information or sub-spells that weren’t current at the interview date).",
                     "",
                     "# 3. Step: Spell prioritisation process. Sorting of parallel spells is determined by spell order, main/side episode (descending), working hours (descending), duration (descending) and splink (ascending order in which the episodes were reported). You may edit this according to your research question(s). The dataset is then reduced to one (the first) spell per person and wave.",
                     "",
                     "# Additional data preparation steps may vary based on the settings configured in the Transform Data tab of the NEPScribe app.",
                     "",
                     "",
                     "rm(list = ls())",
                     "",
                     "# Load necessary libraries",
                     "list.of.packages <- c('dplyr','haven','lubridate','tidyr','dtplyr')",
                     "new.packages <- list.of.packages[!(list.of.packages %in% installed.packages()[,'Package'])] # check if required packages are in installed packages on this machine",
                     "if(length(new.packages)) install.packages (new.packages) # if new.packages contains sth and thus length is > 0, install those new packages",
                     "",
                     "# install nepstools if not installed (package needs to be installed seperately from github) ",
                     "if(!'nepstools' %in% installed.packages()) {",
                     " remotes::install_github('a-helbig/nepstools')",
                     "}",
                     "",
                     "# Add nepstools to list.of.packages",
                     "list.of.packages <- append(list.of.packages, 'nepstools')",
                     "",
                     "# Load all required packages of the given package liste above",
                     "invisible(lapply(list.of.packages, library, character.only = TRUE))",
                     "",
                     "",
                     "# Set working directory and define file paths (adjust as needed)",
                     if(nchar(datapath_local)>0) paste0("datapath = ","'",datapath_local,"/","'"),
                     if(nchar(datapath_local)==0)"datapath = \"\" # Specify local datapath here",
                     if(nchar(datapath_local)>0) paste0("suf_version = ", "'", suf_version,"'", " # Please adjust if necessary"),
                     if(nchar(datapath_local)==0)"suf_version = \"16-0-0\" # Please adjust if necessary",
                     paste0("english = ", english),
                     paste0("sc = ", "'",sc,"'"),
                     "",
                     "# Define variables",
                     "standard_spell_vars <- c('ID_t', 'splink', 'subspell', 'spell', 'spgen', 'spext', 'spstat', 'disagint', 'disagwave', 'wave', 'spms')",
                     "",
                     if(sc=="SC6")"keep_vars <- c('ts1111m', 'ts1111y', 'ts1112m', 'ts1112y', 'ts1112c','ts1311m', 'ts1311y', 'ts1312m', 'ts1312y', 'ts1312c','ts15201_v1', 'ts15201', 'ts1511m', 'ts1511y', 'ts1512m', 'ts1512y', 'ts1512c','ts2111m', 'ts2111y', 'ts2112m', 'ts2112y', 'ts2112c','ts23223_g1', 'ts2311m', 'ts2311y', 'ts2312m', 'ts2312y', 'ts2312c','ts2511m', 'ts2511y', 'ts2512m', 'ts2512y', 'ts2512c','ts2711m', 'ts2711y', 'ts2712m', 'ts2712y', 'ts2712c','ts2911m', 'ts2911y', 'ts2912m', 'ts2912y', 'ts2912c', 'sptype')",
                     if(sc %in% c("SC3", "SC4")) "keep_vars <- c('ts1111m', 'ts1111y', 'ts1112m', 'ts1112y', 'tf1112c','ts1311m', 'ts1311y', 'ts1312m', 'ts1312y', 'ts1312c', 'ts15201', 'ts1511m', 'ts1511y', 'ts1512m', 'ts1512y', 'ts1512c','ts2111m', 'ts2111y', 'ts2112m', 'ts2112y', 'ts2112c', 'ts23223', 'ts2311m', 'ts2311y', 'ts2312m', 'ts2312y', 'ts2312c','ts2511m', 'ts2511y', 'ts2512m', 'ts2512y', 'ts2512c','ts2711m', 'ts2711y', 'ts2712m', 'ts2712y', 'ts2712c','ts2911m', 'ts2911y', 'ts2912m', 'ts2912y', 'ts2912c', 'sptype')",
